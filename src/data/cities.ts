export const getCity = (id: string): City => {
  if (id === 'all') return WORLDWIDE_CITY
  return CITIES.find((c) => c.id === id) ?? CITIES[0]
}

export function resolveCity(value: string) {
  const normalized = value.trim().toLowerCase().replace(/\s+/g, '_')
  if (normalized === 'all' || normalized === 'worldwide' || normalized === 'global') return WORLDWIDE_CITY
  const aliasMap: Record<string, string> = {
    bengaluru: 'bangalore',
    calicut: 'kozhikode',
    cochin: 'kochi',
    ernakulam: 'kochi',
    thiruvananthapuram: 'trivandrum',
    alleppey: 'alappuzha',
    quilon: 'kollam',
    trichur: 'thrissur',
    cannanore: 'kannur',
    palghat: 'palakkad',
    mysuru: 'mysore',
    mangaluru: 'mangalore',
    vizag: 'visakhapatnam',
    ubud: 'bali',
    denpasar: 'bali',
  }
  const alias = aliasMap[normalized] || normalized
  return CITIES.find((c) => c.id === alias || c.name.toLowerCase() === value.toLowerCase())
}
